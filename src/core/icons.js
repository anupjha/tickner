// turns <span data-i="plus"></span> placeholders inside `root` into real icons
export function hydrateIcons(root = document) {
  root.querySelectorAll('[data-i]').forEach(n => {
    n.innerHTML = svg(n.dataset.i, 16);
    n.style.display = 'inline-flex';
    n.removeAttribute('data-i');
  });
}
